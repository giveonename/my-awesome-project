const os = require('os')
const fs = require('fs')
const path = require('path')

function getLocalIP() {
  const interfaces = os.networkInterfaces()
  const candidates = []

  // Skip virtual adapter names
  const virtualPatterns = [
    /vmware/i, /virtualbox/i, /hyper-v/i, /vmnet/i,
    /vethernet/i, /docker/i, /loopback/i, /teredo/i,
    /isatap/i, /6to4/i, /wsl/i, /vEthernet/i
  ]

  for (const name of Object.keys(interfaces)) {
    // Skip adapters whose name matches virtual patterns
    if (virtualPatterns.some(p => p.test(name))) continue

    for (const iface of interfaces[name]) {
      if (iface.internal || iface.family !== 'IPv4') continue
      // Skip WSL and other known virtual IP ranges
      if (/^172\.(2[0-9]|3[0-1])\./.test(iface.address)) continue
      candidates.push({ name, address: iface.address })
    }
  }

  // Prefer typical LAN IPs: 192.168.x.x > 10.x.x.x > 172.16-31.x.x
  const lanPatterns = [/^192\.168\./, /^10\./, /^172\.(1[6-9]|2[0-9]|3[0-1])\./]
  for (const pattern of lanPatterns) {
    const match = candidates.find(c => pattern.test(c.address))
    if (match) return match.address
  }

  // Fallback: first non-loopback IPv4
  return candidates[0]?.address || '127.0.0.1'
}

const ip = getLocalIP()
const port = '8000'
const apiBase = `http://${ip}:${port}/api/v1`

// Write to src/env.ts so it can be imported by the app
const envContent = `// Auto-generated by get-local-ip.cjs — DO NOT EDIT MANUALLY
// Run \`npm run dev:weapp\` or \`npm run build:weapp\` to regenerate
export const API_BASE = '${apiBase}'
export const LOCAL_IP = '${ip}'
`

const outputPath = path.join(__dirname, 'src', 'env.ts')
fs.writeFileSync(outputPath, envContent, 'utf-8')
console.log(`✅ Detected local IP: ${ip}`)
console.log(`✅ API_BASE = ${apiBase}`)
console.log(`✅ Written to src/env.ts`)